"""Subtype specifications, categories A-D (40 subtypes).

Layer-assignment rule used throughout this file (and the other two spec files):
the designated layer is the *narrowest* mechanism that can enforce the violated
property given the concrete tool arguments, not the first one that would notice.

  capability  identity / tenant / operation / resource-instance binding
  workflow    sequencing, replay, delegation, plan and goal integrity
  semantic    instruction source, goal consistency, evasion, deception
  ifc         classification, taint, provenance, egress, aggregation, secrets
  contracts   argument-bound constraints: path scope, amount, recipient, target
  dcbf        rate, volume, concurrency, budget, resource safety envelopes
  hitl        irreversible high-impact actions requiring exact-parameter approval
"""
