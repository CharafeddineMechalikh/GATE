"""Compositional (level 2) and contextual (level 3) attack templates.

Each template is a complete authored scenario. The *last* step is the violating
action; every earlier step must be individually permissible. Earlier steps carry
`state_add` deltas so the intermediate states in the dataset are real, not empty.

A template names the subtype it belongs to only for taxonomy bookkeeping. The
violated property and the enforcing layer are declared explicitly here because a
composition's enforcement point is a design decision, not something derivable
from the final tool call alone.
"""
from __future__ import annotations

from typing import Any, Dict, List, Optional


def st(tool: str, args: Dict[str, Any], target: str, decision: str = "ALLOW",
       layer: str = "none", operation: Optional[str] = None,
       state_add: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
    out: Dict[str, Any] = {"tool": tool, "args": args, "target": target,
                           "decision": decision, "layer": layer}
    if operation:
        out["operation"] = operation
    if state_add:
        out["state_add"] = state_add
    return out


def C(template_id: str, subtype: str, description: str, objective: str, policy: str,
      reason: str, severity: str, steps: List[Dict[str, Any]], *, level: int = 2,
      layer: Optional[str] = None, decision: Optional[str] = None, difficulty: str = "moderate",
      classification: str = "confidential", destination: Optional[Dict[str, str]] = None,
      constraint: Optional[Dict[str, str]] = None, source: str = "agent_plan",
      impact: Optional[Dict[str, Any]] = None, initial_state: Optional[Dict[str, Any]] = None,
      delegation_authorized: bool = True, targets: Optional[List[str]] = None,
      threat_model: str = "compromised or over-reaching agent composing individually permitted tool calls",
      ) -> Dict[str, Any]:
    d: Dict[str, Any] = {
        "template_id": template_id,
        "subtype": subtype,
        "level": level,
        "description": description,
        "objective": objective,
        "policy": policy,
        "reason": reason,
        "severity": severity,
        "steps": steps,
        "enforcing_layer": layer or steps[-1]["layer"],
        "decision": decision or steps[-1].get("decision", "DENY"),
        "difficulty": difficulty,
        "classification": classification,
        "destination": destination,
        "constraint": constraint,
        "source": source,
        "delegation_authorized": delegation_authorized,
        "threat_model": threat_model,
        "targets": targets or [s["target"] for s in steps],
    }
    if impact:
        d["impact"] = impact
    if initial_state:
        d["initial_state"] = initial_state
    return d


def X(template_id: str, subtype: str, description: str, objective: str,
      constraint: str, violated_aspect: str, policy: str, reason: str, severity: str,
      step: Dict[str, Any], *, difficulty: str = "contextual_hard",
      classification: str = "confidential",
      destination: Optional[Dict[str, str]] = None,
      impact: Optional[Dict[str, Any]] = None,
      initial_state: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
    """One contextual case: the action is allowed by static policy, denied by context."""
    return C(
        template_id, subtype, description, objective, policy, reason, severity,
        [step], level=3, difficulty=difficulty, classification=classification,
        destination=destination, impact=impact,
        constraint={
            "original_objective": objective,
            "constraint": constraint,
            "violated_aspect": violated_aspect,
        },
        initial_state=initial_state,
    )


