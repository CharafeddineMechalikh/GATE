"""Coverage-completion scenarios for the authored taxonomy (schema 1.3).

The Phase-1 corpus was atomic-heavy: every category had at least twenty
single-call attacks, but compositional (level 2) and contextual (level 3)
coverage was concentrated in a few categories. This module closes that gap so
each authored category A-J carries at least fifteen compositional and fifteen
contextual attacks on top of its atomic set.

Authoring rules, identical to ``templates.py``:

* the last step violates; every earlier step must be individually permissible;
* compositions carry their own ``state_add`` deltas, so the intermediate states
  are real;
* a contextual case is a single call that static policy would allow and the
  session context does not;
* subtype, layer and policy are declared, never inferred from prose.

Each category spreads its allocation over as many of its ten subtypes as the
declared execution levels allow; ``validate.py`` checks the spread and fails a
category that concentrates a complexity class on one subcategory.
"""
from __future__ import annotations

from typing import Any, Dict, List

from .templates import C, X, st


def _avail(**overrides: Any) -> Dict[str, Any]:
    impact = {"cia": {"confidentiality": "none", "integrity": "full", "availability": "full"},
              "authorization_violation": True, "autonomy_violation": False}
    impact["cia"].update(overrides)
    return impact


def _conf(**overrides: Any) -> Dict[str, Any]:
    impact = {"cia": {"confidentiality": "full", "integrity": "none", "availability": "none"},
              "authorization_violation": True, "autonomy_violation": False}
    impact["cia"].update(overrides)
    return impact


def _dest(channel: str, target: str, trust: str) -> Dict[str, str]:
    return {"channel": channel, "target": target, "trust": trust}


