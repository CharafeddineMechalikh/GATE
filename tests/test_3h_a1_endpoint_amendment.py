"""3H-A1: tests for the primary endpoint and statistical design amendment (design-freeze integrity).

Verifies:
  - oracle feasibility probe: flips located on burned traces only, necessity ablation, no replay errors
  - probe script is GATE-independent (structural source check) and touched no reserved material
  - populations P1/P2/P3 match the frozen 3H-A audit; P2-minus-P1 explicitly accounted
  - revised primary endpoint present; complete-trajectory suppression retained as secondary
  - replay-semantics statements present; no live end-to-end containment claim
  - Wilson half-widths and McNemar power recomputed; 6pp limitation stated without changing the threshold
  - A/B/C preserved byte-for-byte (3G-B manifest hash unchanged); manifest integrity
"""
