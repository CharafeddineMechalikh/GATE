def test_ABC_preserved_and_manifest_integrity():
    gb_man_now = hashlib.sha256(GB_MAN.read_bytes()).hexdigest()
    man = json.loads(MAN.read_text(encoding="utf-8"))
    assert man["artifacts"]["input::3G_B_reproducibility_manifest.json"] == gb_man_now
    assert man["artifacts"]["input::3H_A_reproducibility_manifest.json"] == \
        hashlib.sha256(HA_MAN.read_bytes()).hexdigest()
    assert man["no_execution"] is True
    assert "no 3h-b execution" in man["stop"].lower()
    for rel, h in man["artifacts"].items():
        if rel.startswith("input::"):
            p = RES / rel.split("::", 1)[1]
            assert p.exists(), rel
        elif rel.startswith("script::"):
            p = GU / "scripts" / rel.split("::", 1)[1]
            assert p.exists(), rel
