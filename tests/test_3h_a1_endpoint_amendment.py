import pytest

ROOT = Path(__file__).resolve().parents[1]
GU = ROOT / "gate-union"
RES = GU / "results"

sys.path.insert(0, str(GU / "scripts"))

AM = RES / "3H_A1_endpoint_amendment.json"
PROBE = RES / "3H_A1_oracle_feasibility_probe.json"
MAN = RES / "3H_A1_reproducibility_manifest.json"
