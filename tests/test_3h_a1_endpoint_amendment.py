def test_wilson_half_widths_recomputed(amendment):
    w = amendment["section_4_statistics"]["wilson_half_widths_pp"]
    z = 1.959964
    for name, n in (("P1_primary_security", 300), ("P2_secondary_attack", 629), ("P3_benign", 124)):
        denom = 1 + z * z / n
        half = z * math.sqrt(0.25 / n + z * z / (4 * n * n)) / denom
        assert abs(w[name]["at_p50"] - round(100 * half, 2)) < 0.01
        assert w[name]["n"] == n


def test_mcnemar_limitation_stated_threshold_unchanged(amendment):
    s = amendment["section_4_statistics"]
    assert s["six_pp_limitation"].startswith("STATED, NOT FIXED POST HOC")
    assert "~64%" in s["six_pp_limitation"] and "47%" in s["six_pp_limitation"]
    assert "The 6pp target from 3H-A is retained as predeclared" in s["six_pp_limitation"]
    t = s["mcnemar_power_table_n300"]
    assert t["p_d=0.2, delta=6pp"]["holm_adjusted_alpha_0167"] < 0.8  # underpowered, as stated
    assert t["p_d=0.3, delta=10pp"]["holm_adjusted_alpha_0167"] > 0.7  # powered for ~10pp


